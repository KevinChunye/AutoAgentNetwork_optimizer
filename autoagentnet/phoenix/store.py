"""Immutable payloads, independently checkable receipts, and atomic state snapshots.

Only payloads generated by our tool worker are deserialized. LLMs supply no paths.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import tempfile
from pathlib import Path

from .types import Graph, Operation, Receipt, Status, canonical


def atomic_json(path: str | Path, value) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".pending-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(canonical(value) + "\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def file_sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(65536), b""):
            h.update(block)
    return h.hexdigest()


class ArtifactStore:
    def __init__(self, root: str | Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, key: str, suffix=".joblib") -> Path:
        if not re.fullmatch(r"[0-9a-f]{64}", key):
            raise ValueError("invalid artifact id")
        path = self.root / (key + suffix)
        if path.is_symlink():
            raise ValueError("symlink artifact rejected")
        return path

    def receipt(self, key: str) -> Receipt | None:
        path = self.path(key, ".json")
        if not path.exists():
            return None
        return Receipt.model_validate_json(path.read_text())

    def status(self, op: Operation, graph: Graph, seen=None) -> Status:
        seen = set() if seen is None else seen
        if op.id in seen:
            raise ValueError("cycle")
        seen = seen | {op.id}
        try:
            r = self.receipt(op.id)
            payload = self.path(op.id)
            if r is None or not payload.is_file():
                return Status.MISSING
            if r.operation_id != op.id or r.context != op.context or file_sha(payload) != r.payload_sha256:
                return Status.STALE
            if set(r.parent_payloads) != set(op.parents):
                return Status.STALE
            for key in op.parents:
                parent = graph.operations[key]
                if self.status(parent, graph, seen) != Status.VALID:
                    return Status.STALE
                pr = self.receipt(key)
                if pr is None or r.parent_payloads[key] != pr.payload_sha256:
                    return Status.STALE
            return r.status
        except (ValueError, KeyError, OSError, json.JSONDecodeError):
            return Status.STALE

    def load(self, op: Operation, graph: Graph, allow_unverified=False):
        allowed = (Status.VALID, Status.UNVERIFIED) if allow_unverified else (Status.VALID,)
        if self.status(op, graph) not in allowed:
            raise ValueError("artifact has no usable provenance")
        import joblib
        return joblib.load(self.path(op.id))

    def put(self, op: Operation, graph: Graph, value, cpu_s: float, elapsed_s: float,
            status=Status.UNVERIFIED, api_usd=0.0, executor="cpu") -> Receipt:
        import joblib
        for key in op.parents:
            if self.status(graph.operations[key], graph) != Status.VALID:
                raise ValueError("cannot commit with invalid dependencies")
        target = self.path(op.id)
        fd, name = tempfile.mkstemp(prefix=".payload-", dir=self.root)
        os.close(fd)
        try:
            joblib.dump(value, name)
            os.replace(name, target)
        finally:
            if os.path.exists(name):
                os.unlink(name)
        r = Receipt(operation_id=op.id, payload_sha256=file_sha(target),
                    parent_payloads={p: self.receipt(p).payload_sha256 for p in op.parents},
                    context=op.context, cpu_s=cpu_s, elapsed_s=elapsed_s, status=status,
                    api_usd=api_usd, executor=executor)
        atomic_json(self.path(op.id, ".json"), r.model_dump())
        return r

    def verify(self, op: Operation, graph: Graph) -> Receipt:
        """Validate actual object structure, beyond checksums; no model self-certification."""
        from .workflow import check_payload
        value = self.load(op, graph, allow_unverified=True)
        check_payload(op, value)
        r = self.receipt(op.id)
        r.status = Status.VALID
        atomic_json(self.path(op.id, ".json"), r.model_dump())
        return r
